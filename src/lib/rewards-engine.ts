// src/lib/rewards-engine.ts
//
// Server-side reward issuance + redemption logic — TRANSACTIONAL + IDEMPOTENT.
//
// CRITICAL INVARIANT:
//   This module does NOT open its own Prisma transaction. The caller wraps
//   every call in `withTransaction(async (tx) => { ... })` (from src/lib/db.ts)
//   and passes the `tx` (Prisma.TransactionClient) into these functions. This
//   keeps all reads/writes inside the same snapshot + lock window so:
//     - Balance checks can't race with concurrent redemptions
//     - Ledger entries are committed atomically with the triggering mutation
//       (e.g., the order PICKED_UP transition or the gift PAID transition)
//     - Reward issuance is idempotent — a duplicate key just returns the
//       existing ledger entry rather than issuing duplicate points
//
// Governance (blueprint §17 REWARDS ENGINE + plan §1.D):
//   - Earn fires on PICKED_UP only (prevents cancellation farming)
//   - Ledger-based balance (immutable RewardLedgerEntry rows)
//   - Idempotency via RewardLedgerEntry.idempotencyKey @@unique constraint (Task 1A schema)
//   - One entry per (userId, idempotencyKey)
//   - 365-day expiry via cron (deferred — lazy expiry in MVP)

import { Prisma } from '@prisma/client'
import { buildIdempotencyKey } from './reward-rules'

// ---------------------------------------------------------------------------
// Product-foundation Prisma model delegates
// ---------------------------------------------------------------------------
// Task 1A will add the RewardAccount / RewardLedgerEntry / RewardRedemption
// models to prisma/schema.prisma. Until that schema migration lands, these
// properties don't exist on Prisma.TransactionClient (they're generated by
// `prisma generate` from the schema).
//
// We declare a permissive extension type so rewards-engine compiles against
// the pre-migration client. Once Task 1A applies the schema + runs
// `bun run db:generate`, the real typed delegates replace these `any` stubs
// (the assignment is structurally compatible — `any` is assignable to/from
// any strongly-typed Prisma delegate).
//
// Route handlers (Task 5A) cast their `tx` to `RewardTx` when calling these
// helpers; the cast becomes a no-op once Prisma generates the real types.
export interface RewardPrismaModels {
  rewardAccount: {
    upsert(args: any): Promise<any>
    findUnique(args: any): Promise<any>
    update(args: any): Promise<any>
    create(args: any): Promise<any>
  }
  rewardLedgerEntry: {
    create(args: any): Promise<any>
    findFirst(args: any): Promise<any>
    findMany(args: any): Promise<any>
    aggregate(args: any): Promise<{ _sum: { points: number | null } }>
  }
  rewardRedemption: {
    create(args: any): Promise<any>
    findUnique(args: any): Promise<any>
  }
}

/**
 * Transaction client extended with the product-foundation reward models.
 *
 * Callers wrap their `withTransaction` body in a cast to this type:
 *
 *   await withTransaction(async (tx) => {
 *     await issueReward(tx as unknown as RewardTx, { ... })
 *   })
 *
 * Once Task 1A's schema migration lands + `bun run db:generate` runs,
 * Prisma generates the real typed delegates on Prisma.TransactionClient
 * and the cast becomes a strict no-op.
 */
export type RewardTx = Prisma.TransactionClient & RewardPrismaModels

// ---------------------------------------------------------------------------
// Public row types — mirror the Prisma models (Task 1A schema).
// Defined here so callers don't need to import Prisma types (which don't
// exist until Task 1A lands). When Task 1A generates the Prisma client,
// these interfaces remain structurally compatible.
// ---------------------------------------------------------------------------

export interface RewardAccountRow {
  id: string
  userId: string
  balance: number // points (positive integer)
  lifetimeEarned: number
  lifetimeRedeemed: number
  updatedAt: Date
}

export interface RewardLedgerEntryRow {
  id: string
  userId: string
  type: string // 'EARN' | 'REDEEM' | 'EXPIRE' | 'ADJUST'
  points: number // signed: + for EARN, - for REDEEM/EXPIRE
  orderId: string | null
  ruleId: string | null
  giftId: string | null
  groupOrderId: string | null
  referralUserId: string | null
  idempotencyKey: string
  expiresAt: Date | null
  createdAt: Date
}

export interface RewardRedemptionRow {
  id: string
  userId: string
  ledgerEntryId: string
  rewardType: string // 'PERCENT_DISCOUNT' | 'FIXED_DISCOUNT' | 'FREE_ITEM' | 'VENDOR_SPECIFIC'
  discountValue: string
  orderId: string | null
  redemptionCode: string
  redeemedAt: Date
}

// ---------------------------------------------------------------------------
// Public function param/result types
// ---------------------------------------------------------------------------

export interface IssueRewardParams {
  userId: string
  ruleKey: string
  points: number
  orderId?: string
  giftId?: string
  groupOrderId?: string
  referralUserId?: string
  /** Optional explicit idempotency key (defaults to buildIdempotencyKey(userId, ruleKey, orderId)). */
  idempotencyKey?: string
  /** Optional ISO timestamp for when the earned points expire (EARN entries only). */
  expiresAt?: Date
  /**
   * Optional FK to RewardRule.id (Task 5A additive). When the caller has
   * already resolved the RewardRule row by key, populate this so the ledger
   * entry joins to its rule. Left null when the rule isn't in the DB (the
   * RewardLedgerEntry.ruleId column is nullable per Task 1A schema).
   */
  ruleId?: string
}

export interface IssueRewardResult {
  ledgerEntry: RewardLedgerEntryRow
  newBalance: number
  /** True if this call found an existing entry (no-op). False if a new entry was created. */
  deduplicated: boolean
}

export interface RedeemRewardParams {
  userId: string
  points: number
  orderId?: string
  /** Optional redemption code override; auto-generated if omitted. */
  redemptionCode?: string
  rewardType?: 'PERCENT_DISCOUNT' | 'FIXED_DISCOUNT' | 'FREE_ITEM' | 'VENDOR_SPECIFIC'
  discountValue?: string
}

export interface RedeemRewardResult {
  redemption: RewardRedemptionRow
  newBalance: number
}

