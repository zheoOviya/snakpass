/**
 * Generate a single-use redemption code: `SNZ-RWD-XXXXXX` (6 chars from a
 * legibility-friendly alphabet — no I/O/0/1 to avoid readback confusion).
 *
 * Random, not cryptographically secure — the uniqueness guarantee comes from
 * the RewardRedemption.redemptionCode @@unique constraint (Task 1A schema),
 * so a collision will surface as a P2002 error from Prisma and the caller
 * can retry with a fresh code.
 */
function genRedemptionCode(): string {
  const alphabet = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'
  let code = ''
  for (let i = 0; i < 6; i++) {
    code += alphabet[Math.floor(Math.random() * alphabet.length)]
  }
  return `SNZ-RWD-${code}`
}

/**
 * Lazy-create the reward account row if it doesn't exist (idempotent upsert).
 * Used as a precondition by both issue + redeem flows.
 *
 * MUST be called inside the caller's transaction (uses `tx`).
 */
async function getOrCreateAccount(tx: RewardTx, userId: string): Promise<RewardAccountRow> {
  const account = (await tx.rewardAccount.upsert({
    where: { userId },
    create: {
      userId,
      balance: 0,
      lifetimeEarned: 0,
      lifetimeRedeemed: 0,
    },
    update: {},
  })) as RewardAccountRow
  return account
}

