/**
 * Issue reward points IDEMPOTENTLY.
 *
 * - If a RewardLedgerEntry with the same idempotencyKey already exists for
 *   this user, returns it WITHOUT creating a new entry or modifying the
 *   balance. (This is the "no duplicate reward on retry" guarantee —
 *   blueprint §17.)
 * - Otherwise, creates a new EARN ledger entry and atomically increments the
 *   account balance (within the caller's transaction).
 *
 * MUST be called inside `withTransaction(async (tx) => { ... })` — the caller
 * passes the transaction client as the first argument. This module does NOT
 * open its own transaction (governance: financial mutations must share the
 * caller's snapshot + lock window so balance checks can't race).
 *
 * @param tx      Caller's Prisma.TransactionClient (cast to RewardTx)
 * @param params  Issuance details (userId, ruleKey, points, idempotencyKey, etc.)
 * @returns       The ledger entry + new balance + deduplicated flag
 */
export async function issueReward(
  tx: RewardTx,
  params: IssueRewardParams,
): Promise<IssueRewardResult> {
  const {
    userId,
    ruleKey,
    points,
    orderId,
    giftId,
    groupOrderId,
    referralUserId,
    idempotencyKey,
    expiresAt,
    ruleId,
  } = params

  if (!userId) throw new Error('issueReward: userId required')
  if (!ruleKey) throw new Error('issueReward: ruleKey required')
  if (!Number.isInteger(points) || points <= 0) {
    throw new Error(`issueReward: points must be a positive integer (got ${points})`)
  }

  const key = idempotencyKey ?? buildIdempotencyKey(userId, ruleKey, orderId)

  // 1. Idempotency check — if a ledger entry already exists for this key,
  //    return it WITHOUT issuing duplicate points.
  const existing = (await tx.rewardLedgerEntry.findFirst({
    where: { userId, idempotencyKey: key },
  })) as RewardLedgerEntryRow | null

  if (existing) {
    const account = await getOrCreateAccount(tx, userId)
    return {
      ledgerEntry: existing,
      newBalance: account.balance,
      deduplicated: true,
    }
  }

  // 2. Ensure account exists.
  const account = await getOrCreateAccount(tx, userId)

  // 3. Create the EARN ledger entry (signed +points).
  const ledgerEntry = (await tx.rewardLedgerEntry.create({
    data: {
      userId,
      type: 'EARN',
      points,
      orderId: orderId ?? null,
      ruleId: ruleId ?? null, // optional FK to RewardRule.id (caller-resolved)
      giftId: giftId ?? null,
      groupOrderId: groupOrderId ?? null,
      referralUserId: referralUserId ?? null,
      idempotencyKey: key,
      expiresAt: expiresAt ?? null,
    },
  })) as RewardLedgerEntryRow

  // 4. Atomically increment the cached balance + lifetimeEarned.
  const updated = (await tx.rewardAccount.update({
    where: { userId },
    data: {
      balance: { increment: points },
      lifetimeEarned: { increment: points },
    },
  })) as RewardAccountRow

  return {
    ledgerEntry,
    newBalance: updated.balance,
    deduplicated: false,
  }
}

/**
 * Redeem reward points for a discount code. Validates balance inside the
 * caller's transaction, then atomically:
 *   - Creates a REDEEM ledger entry (signed -points)
 *   - Creates a RewardRedemption row (1:1 with the ledger entry, single-use code)
 *   - Decrements the account balance + increments lifetimeRedeemed
 *
 * MUST be called inside `withTransaction(async (tx) => { ... })`.
 *
 * Throws if the user has insufficient balance. The throw propagates to the
 * caller's transaction, which Prisma rolls back automatically (so no partial
 * state is committed).
 *
 * @param tx      Caller's Prisma.TransactionClient (cast to RewardTx)
 * @param params  Redemption details (userId, points, optional orderId + code override)
 * @returns       The redemption row + new balance
 */
export async function redeemReward(
  tx: RewardTx,
  params: RedeemRewardParams,
): Promise<RedeemRewardResult> {
  const {
    userId,
    points,
    orderId,
    redemptionCode,
    rewardType = 'FIXED_DISCOUNT',
    discountValue = '0',
  } = params

  if (!userId) throw new Error('redeemReward: userId required')
  if (!Number.isInteger(points) || points <= 0) {
    throw new Error(`redeemReward: points must be a positive integer (got ${points})`)
  }

  const account = await getOrCreateAccount(tx, userId)
  if (account.balance < points) {
    throw new Error(
      `redeemReward: insufficient balance (have ${account.balance}, need ${points})`,
    )
  }

  // 1. Create the REDEEM ledger entry (signed -points).
  //    Idempotency key includes a timestamp + random suffix because redemptions
  //    are NOT one-per-order (a user can redeem multiple times against the same
  //    order — e.g., partial redemptions). The idempotency boundary is the
  //    unique ledger entry ID itself.
  const redeemKey =
    buildIdempotencyKey(userId, 'REDEEM', orderId) +
    `:${Date.now()}:${Math.random().toString(36).slice(2, 8)}`

  const ledgerEntry = (await tx.rewardLedgerEntry.create({
    data: {
      userId,
      type: 'REDEEM',
      points: -points,
      orderId: orderId ?? null,
      ruleId: null,
      giftId: null,
      groupOrderId: null,
      referralUserId: null,
      idempotencyKey: redeemKey,
      expiresAt: null,
    },
  })) as RewardLedgerEntryRow

  // 2. Create the single-use redemption code (1:1 with the ledger entry).
  const code = redemptionCode || genRedemptionCode()
  const redemption = (await tx.rewardRedemption.create({
    data: {
      userId,
      ledgerEntryId: ledgerEntry.id,
      rewardType,
      discountValue,
      orderId: orderId ?? null,
      redemptionCode: code,
    },
  })) as RewardRedemptionRow

  // 3. Atomically decrement balance + bump lifetimeRedeemed.
  const updated = (await tx.rewardAccount.update({
    where: { userId },
    data: {
      balance: { decrement: points },
      lifetimeRedeemed: { increment: points },
    },
  })) as RewardAccountRow

  return {
    redemption,
    newBalance: updated.balance,
  }
}

